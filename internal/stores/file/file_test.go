func TestWatchSameSizeRewrite(t *testing.T) {
	a, root := newAdapter(t, Config{WatchInterval: 20 * time.Millisecond})
	p := filepath.Join(root, "tok")
	if err := os.WriteFile(p, []byte(gen(t)), 0o600); err != nil {
		t.Fatal(err)
	}
	fi, _ := os.Stat(p)
	ch, err := a.Watch(t.Context(), stores.Ref{Scheme: "file", Path: "tok"})
	if err != nil {
		t.Fatal(err)
	}
	// Same length, and the old mtime put back: only the digest differs.
	if err := os.WriteFile(p, []byte(gen(t)), 0o600); err != nil {
		t.Fatal(err)
	}
	_ = os.Chtimes(p, fi.ModTime(), fi.ModTime())
	select {
	case c := <-ch:
		if c.Ref.Path != "tok" || c.Kind != stores.Changed {
			t.Errorf("change = %+v", c)
		}
	case <-time.After(3 * time.Second):
		t.Fatal("same-size rewrite with the same mtime not reported")
	}
}

func TestParseOptions(t *testing.T) {
	root := t.TempDir()
	cfg, err := ParseOptions("files", map[string]any{
		"root": root, "format": "dotenv", "trim-newline": "false", "max-size": "64KiB",
		"watch": map[string]any{"interval": "2s"},
	})
	if err != nil {
		t.Fatal(err)
	}
	if cfg.Root != root || cfg.Format != FormatDotenv || cfg.TrimNewline || cfg.MaxSize != 64<<10 || cfg.WatchInterval != 2*time.Second {
		t.Errorf("cfg = %+v", cfg)
	}
	cfg, err = ParseOptions("files", map[string]any{"root": root, "watch.interval": "3s"})
	if err != nil || cfg.WatchInterval != 3*time.Second || !cfg.TrimNewline || cfg.MaxSize != DefaultMaxSize || cfg.Format != FormatAuto {
		t.Errorf("dotted keys/defaults: %+v, %v", cfg, err)
	}
	for name, opts := range map[string]map[string]any{
		"missing root":  {},
		"relative root": {"root": "rel/dir"},
		"bad format":    {"root": root, "format": "yaml"},
		"typo":          {"root": root, "formt": "raw"},
		"bad size":      {"root": root, "max-size": "lots"},
		"bad interval":  {"root": root, "watch.interval": "soon"},
	} {
		if _, err := ParseOptions("files", opts); err == nil {
			t.Errorf("%s accepted", name)
		} else if name == "typo" && !strings.Contains(err.Error(), "did you mean format") {
			t.Errorf("typo error = %v", err)
		}
	}
}

