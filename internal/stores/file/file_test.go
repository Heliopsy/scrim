func plain(v secret.Value) string {
	var s string
	_ = v.Expose(func(b []byte) error { s = string(b); return nil })
	return s
}

func gen(t testing.TB) string {
	t.Helper()
	b := make([]byte, 16)
	if _, err := rand.Read(b); err != nil {
		t.Fatal(err)
	}
	return "file_" + hex.EncodeToString(b)
}

// encode renders fields in format f, the way an operator would write them.
func encode(t storetest.TB, f Format, fields map[string]secret.Value) []byte {
	keys := make([]string, 0, len(fields))
	for k := range fields {
		keys = append(keys, k)
	}
	slices.Sort(keys)
	var b []byte
	switch f {
	case FormatRaw:
		return []byte(plain(fields[RawField]))
	case FormatJSON:
		b = append(b, '{')
		for i, k := range keys {
			if i > 0 {
				b = append(b, ',')
			}
			b, _ = wire.AppendQuoted(b, []byte(k))
			b = append(b, ':')
			var err error
			if b, err = wire.AppendValue(b, fields[k]); err != nil {
				t.Fatalf("encode: %v", err)
			}
		}
		return append(b, '}')
	case FormatDotenv:
		b = append(b, "# generated by the conformance harness\n"...)
		r := strings.NewReplacer(`\`, `\\`, `"`, `\"`, "\n", `\n`, "\r", `\r`, "\t", `\t`, "$", `\$`, "`", "\\`")
		for _, k := range keys {
			b = append(b, "export "+k+`="`+r.Replace(plain(fields[k]))+"\"\n"...)
		}
		return b
	}
	t.Fatalf("encode: unknown format %s", f)
	return nil
}

func writeAtomic(t storetest.TB, tmp, path string, data []byte) {
	if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
		t.Fatalf("mkdir: %v", err)
	}
	f, err := os.CreateTemp(tmp, "seed")
	if err != nil {
		t.Fatalf("temp: %v", err)
	}
	if _, err := f.Write(data); err != nil {
		t.Fatalf("write: %v", err)
	}
	_ = f.Close()
	if err := os.Rename(f.Name(), path); err != nil {
		t.Fatalf("rename: %v", err)
	}
}

func harness(t *testing.T, f Format) storetest.Factory {
	return func(storetest.TB) storetest.Harness {
		root, tmp := t.TempDir(), t.TempDir()
		a, err := New("file", Config{Root: root, Format: f, TrimNewline: true, WatchInterval: 50 * time.Millisecond})
		if err != nil {
			t.Fatal(err)
		}
		h := storetest.Harness{
			Adapter: a,
			Seed: func(t storetest.TB, ref stores.Ref, fields map[string]secret.Value) {
				writeAtomic(t, tmp, filepath.Join(root, ref.Path), encode(t, f, fields))
			},
			Delete: func(t storetest.TB, ref stores.Ref) {
				if err := os.Remove(filepath.Join(root, ref.Path)); err != nil {
					t.Fatalf("delete: %v", err)
				}
			},
			WatchTimeout: 3 * time.Second,
		}
		if f == FormatRaw {
			h.SingleField = RawField
		}
		return h
	}
}

