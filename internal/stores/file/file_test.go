func TestPathConfinement(t *testing.T) {
	outside := t.TempDir()
	v := gen(t)
	if err := os.WriteFile(filepath.Join(outside, "secret"), []byte(v), 0o600); err != nil {
		t.Fatal(err)
	}
	a, root := newAdapter(t, Config{})
	if err := os.Symlink(filepath.Join(outside, "secret"), filepath.Join(root, "link-out")); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink(outside, filepath.Join(root, "dir-out")); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(root, "inside"), []byte(v), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink("inside", filepath.Join(root, "link-in")); err != nil {
		t.Fatal(err)
	}
	rel, _ := filepath.Rel(root, filepath.Join(outside, "secret"))
	for path, kind := range map[string]error{
		rel:                       stores.ErrInvalidRef,
		"../secret":               stores.ErrInvalidRef,
		"a/../../secret":          stores.ErrInvalidRef,
		"/" + outside + "/secret": stores.ErrInvalidRef,
		"link-out":                stores.ErrPermission,
		"dir-out/secret":          stores.ErrPermission,
	} {
		s, err := a.Read(t.Context(), stores.Ref{Scheme: "file", Path: path})
		if err == nil {
			s.Wipe()
			t.Errorf("Read %s escaped the root", path)
			continue
		}
		if !errors.Is(err, kind) {
			t.Errorf("Read %s: %v, want %v", path, err, kind)
		}
		if strings.Contains(err.Error(), v) {
			t.Errorf("Read %s: error leaks content", path)
		}
	}
	// A symlink that stays inside the root works.
	s, err := a.Read(t.Context(), stores.MustParseRef("file://link-in"))
	if err != nil {
		t.Fatalf("Read link-in: %v", err)
	}
	s.Wipe()
	// List never follows a link out of the root.
	ms, err := a.List(t.Context(), stores.Ref{Scheme: "file", Path: "*"})
	if err != nil {
		t.Fatal(err)
	}
	var paths []string
	for _, m := range ms {
		paths = append(paths, m.Ref.Path)
	}
	slices.Sort(paths)
	if !slices.Equal(paths, []string{"inside", "link-in"}) {
		t.Errorf("List = %v", paths)
	}
}

