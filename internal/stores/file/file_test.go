func newAdapter(t *testing.T, cfg Config) (*Adapter, string) {
	t.Helper()
	if cfg.Root == "" {
		cfg.Root = t.TempDir()
	}
	cfg.TrimNewline = true
	a, err := New("file", cfg)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = a.Close() })
	return a, cfg.Root
}

func TestRawTrimsOneNewline(t *testing.T) {
	a, root := newAdapter(t, Config{})
	v := gen(t)
	for name, content := range map[string]string{"lf": v + "\n", "crlf": v + "\r\n", "none": v, "two": v + "\n\n"} {
		if err := os.WriteFile(filepath.Join(root, name), []byte(content), 0o600); err != nil {
			t.Fatal(err)
		}
		s, err := a.Read(t.Context(), stores.Ref{Scheme: "file", Path: name, Field: RawField})
		if err != nil {
			t.Fatal(err)
		}
		want := v
		if name == "two" {
			want = v + "\n"
		}
		if got, _ := s.Field(RawField); plain(got) != want {
			t.Errorf("%s: trailing newline handling wrong", name)
		}
		s.Wipe()
	}
}

func TestAutoFormat(t *testing.T) {
	a, root := newAdapter(t, Config{})
	v := gen(t)
	files := map[string]string{
		"app/.env":            "TOKEN=" + v + "\n",
		"app/.env.local":      "TOKEN=" + v + "\n",
		"app/prod.env":        "TOKEN=" + v + "\n",
		"app/creds.json":      `{"TOKEN":"` + v + `"}`,
		"app/token":           v,
		"app/token.txt":       v + "\n",
		"app/notenv.environ":  v,
		"app/config.json.bak": v,
	}
	for p, c := range files {
		_ = os.MkdirAll(filepath.Dir(filepath.Join(root, p)), 0o700)
		if err := os.WriteFile(filepath.Join(root, p), []byte(c), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	for p := range files {
		field := "TOKEN"
		if detect(p) == FormatRaw {
			field = RawField
		}
		s, err := a.Read(t.Context(), stores.Ref{Scheme: "file", Path: p, Field: field})
		if err != nil {
			t.Errorf("%s: %v", p, err)
			continue
		}
		if got, _ := s.Field(field); plain(got) != v {
			t.Errorf("%s: wrong value", p)
		}
		s.Wipe()
	}
}

func TestDotenvParsing(t *testing.T) {
	v := gen(t)
	src := strings.Join([]string{
		"# comment",
		"",
		"   ",
		"PLAIN=" + v,
		"SPACED = " + v + "   ",
		"COMMENTED=" + v + " # trailing comment",
		"HASH_IN_VALUE=" + v + "#not-a-comment",
		"export EXPORTED=" + v,
		"SINGLE='" + v + " $HOME \\n literal'",
		`DOUBLE="` + v + `\n\t\"\\\$x"`,
		"MULTI=\"line1\nline2\"",
		"SINGLE_MULTI='a",
		"b'",
		"EMPTY=",
		"EMPTY_QUOTED=\"\"",
		"DUP=first",
		"DUP=" + v,
		"dotted.key-name=" + v,
		"CRLF=" + v + "\r",
		"QUOTED_COMMENT=\"" + v + "\" # c",
	}, "\n")
	got, err := parseDotenv([]byte(src))
	if err != nil {
		t.Fatal(err)
	}
	defer wipeAll(got)
	want := map[string]string{
		"PLAIN": v, "SPACED": v, "COMMENTED": v, "HASH_IN_VALUE": v + "#not-a-comment", "EXPORTED": v,
		"SINGLE": v + ` $HOME \n literal`, "DOUBLE": v + "\n\t\"\\$x", "MULTI": "line1\nline2",
		"SINGLE_MULTI": "a\nb", "EMPTY": "", "EMPTY_QUOTED": "", "DUP": v, "dotted.key-name": v, "CRLF": v,
		"QUOTED_COMMENT": v,
	}
	for k, w := range want {
		if g, ok := got[k]; !ok || plain(g) != w {
			t.Errorf("%s: wrong or missing", k)
		}
	}
	if len(got) != len(want) {
		t.Errorf("parsed %d keys, want %d", len(got), len(want))
	}
}

func TestDotenvErrorsNameLinesNotContent(t *testing.T) {
	v := gen(t)
	for _, src := range []string{
		"OK=1\n" + v,
		"OK=1\nBAD KEY=" + v,
		"1BAD=" + v,
		"OPEN=\"" + v,
		"OPEN='" + v,
		"AFTER=\"" + v + "\" trailing",
	} {
		_, err := parseDotenv([]byte(src))
		if err == nil {
			t.Errorf("malformed dotenv accepted")
			continue
		}
		if strings.Contains(err.Error(), v) || !strings.Contains(err.Error(), "line") {
			t.Errorf("error %q leaks content or names no line", err)
		}
	}
}

func TestJSONParsing(t *testing.T) {
	v := gen(t)
	got, err := parseJSON([]byte(`{"s":"` + v + `é","n":42,"b":true,"o":{"k":"x"},"z":null}`))
	if err != nil {
		t.Fatal(err)
	}
	defer wipeAll(got)
	for k, w := range map[string]string{"s": v + "é", "n": "42", "b": "true", "o": `{"k":"x"}`} {
		if plain(got[k]) != w {
			t.Errorf("%s = wrong", k)
		}
	}
	if _, ok := got["z"]; ok {
		t.Errorf("null field kept")
	}
	for _, bad := range []string{`["` + v + `"]`, `{"a":"` + v, `"` + v + `"`, `{"a":` + v + `}`} {
		_, err := parseJSON([]byte(bad))
		if err == nil {
			t.Errorf("invalid JSON accepted")
		} else if strings.Contains(err.Error(), v) || strings.Contains(err.Error(), "file_") {
			t.Errorf("JSON error leaks content: %q", err)
		}
	}
}

