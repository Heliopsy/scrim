// TestWriteToReadOnlySource: a write is refused with an error saying the
// file source is read-only, and nothing is created.
func TestWriteToReadOnlySource(t *testing.T) {
	a, root := newAdapter(t, Config{})
	v := gen(t)
	val := secret.FromString(v)
	_, err := a.Write(t.Context(), stores.MustParseRef("file://new"), map[string]secret.Value{RawField: val}, stores.WriteOptions{})
	if !errors.Is(err, stores.ErrUnsupported) || !strings.Contains(err.Error(), "file source is read-only") || strings.Contains(err.Error(), v) {
		t.Errorf("Write = %v", err)
	}
	if _, err := os.Stat(filepath.Join(root, "new")); !errors.Is(err, os.ErrNotExist) {
		t.Errorf("a refused write created a file")
	}
	if val.Wiped() {
		t.Errorf("refused write wiped the caller's value")
	}
}

