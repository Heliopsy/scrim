// envViewPasswd makes the fsview agent read through the password-database
// home; only tests that mount a temporary directory over it set it, so no
// test reads the real home.
const envViewPasswd = "SCRIM_RUN_TEST_PASSWD_HOME"

// envViewReal names a real credential file the fsview agent reads by its
// absolute path.
const envViewReal = "SCRIM_RUN_TEST_REAL_FILE"

// viewReport is what the fsview test agent saw.
type viewReport struct {
	UID       int    `json:"uid"`
	HomeAWS   string `json:"home_aws"`
	PasswdAWS string `json:"passwd_aws"`
	SSHKey    string `json:"ssh_key"`
	CatSSHKey string `json:"cat_ssh_key"`
	SSHPub    string `json:"ssh_pub"`
	Doctl     string `json:"doctl"`
	Notes     string `json:"notes"`
	RealAWS   string `json:"real_aws"`
	Unmount   string `json:"unmount"`
	Nested    string `json:"nested"`
	XDGConfig string `json:"xdg_config"`
	Agent     string `json:"agent"`
}

// agentFSView reads the credential paths a tool would read and reports what
// it found. Decoys and placeholders are generated by the test, never real.
func agentFSView() int {
	home := os.Getenv("HOME")
	read := func(p string) string {
		b, err := os.ReadFile(p)
		if err != nil {
			return "ERR: " + err.Error()
		}
		return string(b)
	}
	r := viewReport{UID: os.Getuid(), XDGConfig: os.Getenv("XDG_CONFIG_HOME")}
	r.HomeAWS = read(filepath.Join(home, ".aws/credentials"))
	// Like a tool that ignores HOME and asks the password database.
	if os.Getenv(envViewPasswd) == "1" {
		if u, err := user.Current(); err == nil {
			r.PasswdAWS = read(filepath.Join(u.HomeDir, ".aws/credentials"))
		} else {
			r.PasswdAWS = "ERR: " + err.Error()
		}
	}
	key := filepath.Join(home, ".ssh/id_ed25519")
	r.SSHKey = read(key)
	if out, err := exec.Command("cat", key).CombinedOutput(); err != nil {
		r.CatSSHKey = "FAIL: " + strings.TrimSpace(string(out))
	} else {
		r.CatSSHKey = "OK: " + string(out)
	}
	r.SSHPub = read(key + ".pub")
	r.Doctl = read(filepath.Join(home, ".config/doctl/config.yaml"))
	r.Notes = read(filepath.Join(home, "notes.txt"))
	if p := os.Getenv(envViewReal); p != "" {
		r.RealAWS = read(p)
	}
	r.Unmount = tryUnmount(filepath.Join(home, ".aws/credentials"))
	// A namespace of its own, where the agent holds every capability:
	// the kernel keeps the inherited mounts locked together.
	if unshare, err := exec.LookPath("unshare"); err == nil {
		out, err := exec.Command(unshare, "--user", "--map-root-user", "--mount", "sh", "-c",
			`umount "$HOME/.aws/credentials" 2>&1; umount -l "$HOME/.ssh/id_ed25519" 2>&1; cat "$HOME/.aws/credentials" "$HOME/.ssh/id_ed25519" 2>&1`).CombinedOutput()
		r.Nested = fmt.Sprintf("%s (%v)", out, err)
	}
	c := localapi.FromEnv()
	if id, err := c.WhoAmI(context.Background()); err == nil {
		r.Agent = id.Agent
	} else {
		r.Agent = "ERR: " + err.Error()
	}
	c.Close()
	return printJSON(r)
}

func printJSON(v any) int {
	if err := json.NewEncoder(os.Stdout).Encode(v); err != nil {
		return 2
	}
	return 0
}

// viewHome is a home directory with decoy credentials at fixed paths.
type viewHome struct {
	dir, decoy, pub, notes string
}

func randHex(t *testing.T) string {
	b := make([]byte, 12)
	if _, err := rand.Read(b); err != nil {
		t.Fatal(err)
	}
	return hex.EncodeToString(b)
}

// plantHome writes decoys into dir: what a real home would hold.
func plantHome(t *testing.T, dir string) viewHome {
	t.Helper()
	h := viewHome{dir: dir, decoy: "DECOY-" + randHex(t), pub: "ssh-ed25519 PUBLIC-" + randHex(t), notes: "notes " + randHex(t)}
	files := map[string]string{
		".aws/credentials":          "[default]\naws_secret_access_key = " + h.decoy + "\n",
		".ssh/id_ed25519":           "-----BEGIN OPENSSH PRIVATE KEY-----\n" + h.decoy + "\n",
		".ssh/id_ed25519.pub":       h.pub,
		".config/doctl/config.yaml": "access-token: " + h.decoy + "\n",
		"notes.txt":                 h.notes,
	}
	for rel, data := range files {
		p := filepath.Join(dir, rel)
		if err := os.MkdirAll(filepath.Dir(p), 0o700); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(data), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	return h
}

const viewPlaceholder = "SCRIM_AWS_SECRET_ACCESS_KEY"

// viewProfiles renders an aws profile that generates credentials and a
// doctl one that hides its config, as the built-ins do.
func viewProfiles(_ context.Context, _ string, sess profiles.Session) (*profiles.Rendered, error) {
	return &profiles.Rendered{
		Profiles: []string{"aws", "doctl"},
		Files: []profiles.GeneratedFile{{Path: "aws/credentials", Profile: "aws",
			Data: []byte("[default]\naws_secret_access_key = " + viewPlaceholder + "\n")}},
		Paths: []profiles.PathView{
			{Home: ".aws/credentials", Generated: filepath.Join(sess.Dir, "aws", "credentials"), Profile: "aws"},
			{Home: ".config/doctl/config.yaml", Profile: "doctl"},
		},
		Hosts: map[string][]string{},
	}, nil
}

// runView runs the fsview agent under scrim run with the given view and
// returns what it saw and scrim run's stderr.
func runView(t *testing.T, home viewHome, fo FSViewOptions, extraEnv ...string) (viewReport, string, error) {
	t.Helper()
	h := newHarness(t, true)
	env := baseEnv(t, append([]string{envAgent + "=fsview", envViewReal + "=" + filepath.Join(home.dir, ".aws/credentials")}, extraEnv...)...)
	env = setEnv(env, "HOME", home.dir)
	env = setEnv(env, "XDG_CONFIG_HOME", filepath.Join(home.dir, ".config"))
	if fo.Hide == nil {
		fo.Hide = slices.Clone(fsview.DefaultHide)
	}
	var out, errb syncBuf
	rt := t.TempDir()
	err := Run(context.Background(), Options{
		Command: []string{selfAgent(t)}, Environ: env, Daemon: h.daemon(), Stdout: &out, Stderr: &errb,
		RuntimeDir: rt, Profiles: viewProfiles, FSView: fo,
	})
	var r viewReport
	if err == nil {
		if jerr := json.Unmarshal([]byte(out.String()), &r); jerr != nil {
			t.Fatalf("agent output %q: %v\nstderr: %s", out.String(), jerr, errb.String())
		}
	}
	if left, _ := os.ReadDir(rt); len(left) != 0 {
		t.Errorf("session directory left behind: %v", left)
	}
	return r, errb.String(), err
}

func setEnv(env []string, k, v string) []string {
	out := make([]string, 0, len(env)+1)
	for _, kv := range env {
		if !strings.HasPrefix(kv, k+"=") {
			out = append(out, kv)
		}
	}
	return append(out, k+"="+v)
}

// noDecoy fails when any field of the report holds the decoy.
func noDecoy(t *testing.T, r viewReport, decoy string, except ...string) {
	t.Helper()
	b, _ := json.Marshal(r)
	var m map[string]any
	_ = json.Unmarshal(b, &m)
	for k, v := range m {
		if s, ok := v.(string); ok && strings.Contains(s, decoy) && !slices.Contains(except, k) {
			t.Errorf("%s: the session read the real file: %q", k, s)
		}
	}
}

func unavailable(context.Context, string) fsview.Availability {
	return fsview.Availability{Reason: "test host without namespaces"}
}

// TestFSViewHomeMirror is the fallback without namespaces (tasks.md 10a.8):
// HOME points at a mirror without the real credential files, and the real
// files stay readable by absolute path, a gap status reports.
func TestFSViewHomeMirror(t *testing.T) {
	if runtime.GOOS == "windows" {
		t.Skip("Windows has no session filesystem view")
	}
	home := plantHome(t, t.TempDir())
	for _, mode := range []string{fsview.ModeHome, fsview.ModeAuto} {
		t.Run(mode, func(t *testing.T) {
			r, stderr, err := runView(t, home, FSViewOptions{Mode: mode, Probe: unavailable, PasswdHome: home.dir})
			if err != nil {
				t.Fatalf("run: %v\n%s", err, stderr)
			}
			if !strings.Contains(r.HomeAWS, viewPlaceholder) {
				t.Errorf("~/.aws/credentials in the session = %q, want the placeholder", r.HomeAWS)
			}
			if !strings.HasPrefix(r.SSHKey, "ERR:") || !strings.HasPrefix(r.CatSSHKey, "FAIL:") {
				t.Errorf("hidden key readable: read %q, cat %q", r.SSHKey, r.CatSSHKey)
			}
			if !strings.HasPrefix(r.Doctl, "ERR:") {
				t.Errorf("hidden doctl config readable: %q", r.Doctl)
			}
			if r.SSHPub != home.pub || r.Notes != home.notes {
				t.Errorf("the rest of the home changed: pub %q, notes %q", r.SSHPub, r.Notes)
			}
			if !strings.HasPrefix(r.XDGConfig, filepath.Join(os.TempDir())) || strings.HasPrefix(r.XDGConfig, home.dir) {
				t.Errorf("XDG_CONFIG_HOME = %q, want it moved into the session home", r.XDGConfig)
			}
			if r.Agent != "dev" {
				t.Errorf("agent not identified: %q", r.Agent)
			}
			// The documented gap: the real file by its absolute path.
			noDecoy(t, r, home.decoy, "real_aws")
			if !strings.Contains(r.RealAWS, home.decoy) {
				t.Errorf("real file by absolute path = %q; the gap the docs list is gone, update them", r.RealAWS)
			}
			if !strings.Contains(stderr, "filesystem view: HOME points at a mirror") || !strings.Contains(stderr, "not covered:") {
				t.Errorf("no fallback warning with gaps: %q", stderr)
			}
			if mode == fsview.ModeAuto && !strings.Contains(stderr, "test host without namespaces") {
				t.Errorf("fallback reason missing: %q", stderr)
			}
		})
	}
	if b, _ := os.ReadFile(filepath.Join(home.dir, ".aws/credentials")); !strings.Contains(string(b), home.decoy) {
		t.Error("the real file changed")
	}
}

// TestFSViewOff is the control: without the view the agent reads the
// decoy, so the tests above would catch a view that does nothing.
func TestFSViewOff(t *testing.T) {
	if runtime.GOOS == "windows" {
		t.Skip("Windows has no session filesystem view")
	}
	home := plantHome(t, t.TempDir())
	r, stderr, err := runView(t, home, FSViewOptions{Mode: fsview.ModeOff, PasswdHome: home.dir})
	if err != nil {
		t.Fatalf("run: %v\n%s", err, stderr)
	}
	if !strings.Contains(r.HomeAWS, home.decoy) || !strings.Contains(r.SSHKey, home.decoy) {
		t.Fatalf("without the view the agent should read the planted files: %+v", r)
	}
}

// TestFSViewNamespaceRequiredRefuses: run.fs-view namespace on a host
// without namespaces does not start the agent.
func TestFSViewNamespaceRequiredRefuses(t *testing.T) {
	if runtime.GOOS == "windows" {
		t.Skip("Windows has no session filesystem view")
	}
	home := plantHome(t, t.TempDir())
	_, stderr, err := runView(t, home, FSViewOptions{Mode: fsview.ModeNamespace, Probe: unavailable, PasswdHome: home.dir})
	if !errors.Is(err, ErrRefused) || !strings.Contains(err.Error(), "test host without namespaces") {
		t.Fatalf("want a refusal naming the reason, got %v\n%s", err, stderr)
	}
}

// TestFSViewPrintEnv shows the view without writing anything.
func TestFSViewPrintEnv(t *testing.T) {
	if runtime.GOOS == "windows" {
		t.Skip("Windows has no session filesystem view")
	}
	home := plantHome(t, t.TempDir())
	h := newHarness(t, true)
	env := setEnv(baseEnv(t), "HOME", home.dir)
	plan, err := PrintEnv(context.Background(), Options{
		Command: []string{"claude"}, Environ: env, Daemon: h.daemon(), Profiles: viewProfiles,
		FSView: FSViewOptions{Mode: fsview.ModeAuto, Hide: slices.Clone(fsview.DefaultHide), Probe: unavailable, PasswdHome: home.dir},
	})
	if err != nil {
		t.Fatal(err)
	}
	v := plan.FSView
	if v == nil || v.Mode != fsview.ModeHome || v.Fallback == "" {
		t.Fatalf("view = %+v, want the home fallback", v)
	}
	got := map[string]string{}
	for _, e := range v.Entries {
		got[e.Home] = e.Origin
		if e.Home == ".aws/credentials" && e.Hidden() {
			t.Error("aws credentials hidden instead of replaced")
		}
	}
	want := map[string]string{".aws/credentials": "aws", ".config/doctl/config.yaml": "doctl", ".ssh/id_ed25519": fsview.HideOrigin}
	for k, o := range want {
		if got[k] != o {
			t.Errorf("entry %s from %q, want %q (entries %v)", k, got[k], o, got)
		}
	}
	if _, ok := got[".ssh/id_ed25519.pub"]; ok {
		t.Error("public key hidden")
	}
	if _, err := os.Stat(filepath.Join(home.dir, "..", "fsview")); err == nil {
		t.Error("print-env wrote files")
	}
}
